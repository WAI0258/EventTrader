interface LocaleContextValue {
  locale: PMConsoleLocale;
  setLocale: (locale: PMConsoleLocale) => void;
  toggleLocale: () => void;
  t: (source: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function readStoredLocale(): PMConsoleLocale {
  try {
    return window.localStorage.getItem(PM_CONSOLE_LOCALE_STORAGE_KEY) === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

function persistLocale(locale: PMConsoleLocale) {
  try {
    window.localStorage.setItem(PM_CONSOLE_LOCALE_STORAGE_KEY, locale);
  } catch {
    // Storage can be unavailable in private or embedded browser contexts.
  }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<PMConsoleLocale>(readStoredLocale);
  const setLocale = (nextLocale: PMConsoleLocale) => {
    setLocaleState(nextLocale);
    persistLocale(nextLocale);
  };
  const value = useMemo(
    () => ({
      locale,
      setLocale,
      toggleLocale: () => setLocale(locale === "en" ? "zh-CN" : "en"),
      t: (source: string) => (locale === "zh-CN" ? (zhCN[source] ?? source) : source),
    }),
    [locale],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  return useContext(LocaleContext) ?? {
    locale: "en",
    setLocale: () => undefined,
    toggleLocale: () => undefined,
    t: (source) => source,
  };
}
